// ---------- PACK SIZES BY BRAND ----------
// The pack sizes a customer can choose on each product.
// Mops / tools and the urinal screen keep their own sizes (they are not liquids).
const PACKS_BY_BRAND = {
  "diversey-taski": ["5 L"],
  reva: ["1 L", "5 L"],
  miraclean: ["1 L", "5 L"],
};
const KEEP_OWN_PACKS = new Set(["crew-urinal-screen"]);

for (const p of products) {
  const sizes = PACKS_BY_BRAND[p.brand];
  if (!sizes || p.category === "tools" || KEEP_OWN_PACKS.has(p.id)) continue;
  // keep any price already entered for a size
  p.packs = sizes.map((size) => ({ size, price: p.packs.find((k) => k.size === size)?.price ?? null }));
}

export const productById = Object.fromEntries(products.map((p) => [p.id, p]));
export const brandById = Object.fromEntries(brands.map((b) => [b.id, b]));
export const categoryById = Object.fromEntries(categories.map((c) => [c.id, c]));

export const productsOfBrand = (id) =>
  products.filter((p) => p.brand === id || (id === "cleaning-tools" && p.category === "tools") || (id === "dustbins" && p.category === "dustbins"));

export const productsOfCategory = (id) => products.filter((p) => p.category === id);

export const topSelling = products.filter((p) => p.top);

export function searchProducts(q) {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  const words = s.split(/\s+/);
  return products.filter((p) => {
    const hay = [p.name, p.short, brandById[p.brand]?.name, categoryById[p.category]?.name, ...p.uses, ...p.where].join(" ").toLowerCase();
    return words.every((w) => hay.includes(w));
  });
}

